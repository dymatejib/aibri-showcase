"""ГЕОМЕТРИЯ СТРАНИЦЫ И БЕСПЛАТНЫЙ ЛОКАЛЬНЫЙ OCR — снять с фотографии ДОСЛОВНЫЙ
текст и восстановить СТРОКИ документа.

Слой сознательно живёт в `recognition`, а не в `shifts`: наклон кадра и сборка
строк по базовой линии — свойство БУМАГИ, а не кассовой смены. Пока эти функции
лежали рядом с разбором Z-отчётов, ими же читались накладные — то есть модуль
«смены» держал геометрию всех документов проекта. Один смысл — одно место.

Что здесь происходит и почему это не тривиально:

  · Vision отдаёт фрагменты ПО КОЛОНКАМ (сначала все подписи, потом все значения).
    Табличный документ от такой выдачи разваливается: нужны СТРОКИ.
  · Строка — это набор фрагментов с одной базовой линией `y − наклон·x`. Наклон
    кадра ПОДБИРАЕТСЯ, а не предполагается: фотографию делают руками.
  · Наружу всегда уходит ОТВЕТ, а не исключение: `ocr_image` возвращает
    `(текст, ошибка)`, и вызывающий по этой паре выбирает следующий слой.

ПЛАТФОРМА. Бесплатный локальный распознаватель — это macOS Vision через пакет
`ocrmac`, и он существует ТОЛЬКО на macOS. Поэтому `ocrmac` нигде не импортируется
на уровне модуля: `import aibri.recognition.ocr` обязан проходить на любой ОС,
иначе Linux и Windows потеряли бы вместе с фото-путём весь текстовый разбор
документов, сверку смен и тесты. Импорт живёт ВНУТРИ двух функций ниже, и обе
честно отвечают «нет распознавателя» вместо падения.
"""
import os

LOCAL_OCR_NOTE = ("локальный OCR доступен только на macOS (Vision через пакет "
                  "ocrmac) — текстовый путь работает везде")


def recognizer_ready():
    """Доступен ли БЕСПЛАТНЫЙ локальный распознаватель. Функция существует, чтобы
    интерфейс не врал: плашка «разбираю архив» когда-то показывалась ВСЕГДА, а
    разбирать было нечем — бесплатный слой был физически недостижим из фонового
    процесса, и архив разбирался только руками.

    Один ответ на весь проект: и интерфейс, и тесты спрашивают ЗДЕСЬ, а не сравнивают
    `sys.platform` каждый у себя. На маке без установленного `ocrmac` ответ такой же
    честный «нет», как на Linux."""
    try:
        from ocrmac import ocrmac as _o  # noqa: F401
        return True
    except Exception:                            # noqa: BLE001 — нет пакета, нет Vision, нет прав
        return False


def rows_by_baseline(items, slope):
    """Фрагменты → СТРОКИ ДОКУМЕНТА при заданном наклоне кадра.

    Строка — это набор фрагментов с одной базовой линией `y − наклон·x`. Порог
    склейки берётся от высоты самого фрагмента: у крупного заголовка он больше, у
    мелкого подвала меньше — одной константы на весь документ не бывает.

    Фрагмент — кортеж `(текст, x, y, высота)` в долях кадра."""
    out, cur, cur_y = [], [], None
    for it in sorted(items, key=lambda i: -(i[2] - slope * i[1])):
        y = it[2] - slope * it[1]
        if cur_y is not None and abs(y - cur_y) <= it[3] * 0.7:
            cur.append(it)
        else:
            if cur:
                out.append(cur)
            cur, cur_y = [it], y
    if cur:
        out.append(cur)
    return out


def frame_slope(items, limit=0.3, step=0.005):
    """НАКЛОН КАДРА (dy/dx) — фото делают руками, и бумага почти никогда не лежит
    ровно.

    Класс ошибки, ради которого это существует: при наклоне 8° по ширине таблицы
    правая колонка уезжает вниз на несколько высот строки, и группировка «по
    горизонтали» сшивает в одну ленту фрагменты РАЗНЫХ строк документа —
    количество одного товара встаёт рядом с суммой другого. Ни один дальнейший
    разбор такого уже не спасёт.

    Наклон не вычисляется по одной паре фрагментов (любая пара может оказаться
    подписью в подвале), а ПОДБИРАЕТСЯ: перебираем углы и берём тот, при котором
    фрагменты собираются в наименьшее число самых плотных строк (максимум Σ n²).
    Ничья — за меньшим углом: ровный кадр остаётся ровным."""
    best, best_score = 0.0, None
    k = int(limit / step)
    for i in range(-k, k + 1):
        s = i * step
        score = sum(len(r) ** 2 for r in rows_by_baseline(items, s))
        if best_score is None or score > best_score \
                or (score == best_score and abs(s) < abs(best)):
            best, best_score = s, score
    return best


def ocr_image(path):
    """(текст, ошибка). Локальный OCR через macOS Vision.

    Vision отдаёт фрагменты ПО КОЛОНКАМ (сначала все подписи, потом все значения) —
    табличный документ от этого разваливается. Реконструируем СТРОКИ ДОКУМЕНТА по
    рамкам: подбор наклона кадра (`frame_slope`), группировка по базовой линии,
    внутри строки сортировка по горизонтали, склейка через « | ». Именно поэтому
    весь дальнейший разбор умеет читать «ячейки» — их создаёт этот слой."""
    if not path:
        return None, "no_path"
    if not os.path.exists(path):
        return None, "file_missing"
    try:
        from ocrmac import ocrmac as _ocrmac
    except Exception as exc:                     # noqa: BLE001
        # не только ImportError: на не-маке пакета нет вовсе, а на маке он тянет
        # pyobjc — тот умеет падать своими ошибками. Наружу в любом случае уходит
        # ответ, а не исключение: вызывающий выбирает следующий слой распознавания.
        return None, f"ocrmac_missing: {exc} ({LOCAL_OCR_NOTE})"
    try:
        ann = _ocrmac.OCR(path, recognition_level="accurate",
                          language_preference=["ru-RU", "en-US"]).recognize()
    except Exception as exc:                     # noqa: BLE001
        return None, f"ocr_failed: {exc}"
    items = []
    for a in ann:
        if not (a and a[0]):
            continue
        bbox = a[2] if len(a) > 2 and a[2] is not None else None
        if bbox is not None and len(bbox) >= 4:
            x, y, _w, h = (float(bbox[0]), float(bbox[1]), float(bbox[2]), float(bbox[3]))
            items.append((a[0], x, y + h / 2, max(h, 0.012)))
        else:
            items.append((a[0], 0.0, 0.0, 0.012))
    rows = rows_by_baseline(items, frame_slope(items))
    lines = [" | ".join(t for t, *_ in sorted(row, key=lambda r: r[1])) for row in rows]
    return "\n".join(lines), None
