"""ЕДИНЫЙ ФОРМАТ ДЕНЕГ.

Было: «1 234 567» форматировалось ДЕВЯТЬЮ способами в питоне
(`f"{n:,}".replace(",", " ")` россыпью по роутам и сервисам) и ещё тремя в
скриптах страницы. Один из девяти уже разъехался по-настоящему — расчёт налогов
разделял тысячи НЕРАЗРЫВНЫМ пробелом (\\u00a0), все остальные обычным, и на
экране это было видно глазом. Теперь источник один, и грепстраж
(`guards/grep_guard_single_impl.py`) не даёт завестись второму.
"""


def money(v) -> str:
    """Полное число с пробелом-разделителем тысяч: 1234567 → «1 234 567».
    Дробь (тийины) сохраняется и показывается запятой: 9165.33 → «9 165,33»,
    целое — без хвоста: 9165.0 → «9 165» («считаем точно, не округляем»).
    Не число — отдаём как есть (чтобы «—», «уточняется» проходили насквозь)."""
    try:
        n = round(float(v), 2)
    except (TypeError, ValueError):
        return v
    neg = "-" if n < 0 else ""
    n = abs(n)
    if n == int(n):
        return neg + f"{int(n):,}".replace(",", " ")
    return neg + f"{n:,.2f}".replace(",", " ").replace(".", ",")


def parse_money(v) -> float:
    """ЕДИНЫЙ разбор денежной суммы из ввода владельца: точка И запятая — одно и то
    же, пробелы-разделители убираются, дробь СОХРАНЯЕТСЯ (до 2 знаков, не округляем
    до целого сума), значение не отрицательное. Пусто/мусор → 0.0.
    Владельцу больше не важно, поставил он точку или запятую."""
    if v is None:
        return 0.0
    s = str(v).strip().replace(" ", "").replace(" ", "").replace(",", ".")
    if not s:
        return 0.0
    try:
        return max(0.0, round(float(s), 2))
    except (TypeError, ValueError):
        return 0.0


def money_short(v) -> str:
    """Деньги-ВИТРИНА: до 1 млн — «128,3 к», дальше — «3,13 млн» (до 10 млн две
    цифры после запятой, дальше одна). Знак минус сохраняется. Ввод и платёжные
    документы остаются ПОЛНЫМИ числами; это только для компактного показа —
    единственная точка фильтра, меняется тут и только тут."""
    try:
        n = float(v)
    except (TypeError, ValueError):
        return v
    neg = "-" if n < 0 else ""
    n = abs(n)
    if n >= 1_000_000:
        m = n / 1_000_000
        st = f"{m:.2f}" if m < 10 else f"{m:.1f}"
        return f"{neg}{st.rstrip('0').rstrip('.').replace('.', ',')} млн"
    if n >= 1_000:
        st = f"{n / 1_000:.1f}"
        return f"{neg}{st.rstrip('0').rstrip('.').replace('.', ',')} к"
    return f"{neg}{int(n)}"
