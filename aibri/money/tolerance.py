"""ЕДИНЫЙ ЗАКОН ДОПУСКА (L-04v2).

Зачем: какое-то время в коде жили ТРИ РАЗНЫХ допуска на одно и то же расхождение
«приход ↔ заказ ↔ печатный итог», и владелец видел то плашку, то тишину на
одинаковых данных:

  1) `1 сум`   — гейт закрытия приёмки и судья выбора разбора накладной;
  2) `12 сум`  — «объяснённые копейки» строк-зеркал (живой случай: 12 шт × Δ1 сум/шт);
  3) `0,1 %`   — предложенный процентный инвариант.

Третий вариант ОПАСЕН как СУДЬЯ РАЗБОРА: на документе с итогом 1 400 000 сум
0,1 % = 1 400 сум, и ОБРЕЗАННЫЙ разбор (3 строки из 4, потеря строки на 380 сум)
«сходился» с печатным итогом и побеждал полный. Проверено замером и закреплено
фикстурой `inv_08_percent_judge`. Поэтому закон разделяет РАЗНЫЕ вопросы и НЕ
смешивает их:

  **A. СУДЬЯ РАЗБОРА** (какой из кандидатов правильно прочитал документ) — допуск
     копеечный и жёсткий: `judge_eps()`. Здесь процент недопустим: он оправдывает
     потерю строки.
  **B. ВЕРДИКТ ВЛАДЕЛЬЦУ** (гасить ли плашку расхождения) — `covered()`:
     гасит ТОЛЬКО то, что объяснено арифметикой округления —
       · пол: 1 сум на строку документа (каждая строка бумаги округлена до сума),
       · плюс УЖЕ ПОСЧИТАННЫЕ копейки строк-зеркал (второй арифметики не заводим);
     и НЕ гасит НИКОГДА (`hard=True`):
       · «итог не по колонкам» (печатный ИТОГО документа против Σ строк — это либо
         потерянная строка, либо ошибка поставщика: вопрос владельцу, не округление),
       · недовоз/недостача количества,
       · канал-расхождения денег (проводка оплаты, выписка банка).
  **C. ГЕЙТ ДЕНЕГ ПРИЁМКИ** (сошлись ли проводки с суммой прихода) — `pay_eps()`.
  **D. АРИФМЕТИКА ОДНОЙ СТРОКИ** (`row_eps` / `pair_eps`) — см. ниже: это про
     произведение внутри строки, а не про расхождение документа.

ДОМ У ДОПУСКА ОДИН. Числа, живущие по месту вызова, разъезжаются молча — ровно так
в проекте появились три разных допуска на одно расхождение, с которых начинается
этот докстринг. Поэтому здесь лежат ВСЕ пороги сравнения денег, включая те, что
нужны парсеру построчно.

Модуль без импортов и без БД — его зовут и парсер накладной, и сервис приёмки,
и экран. Один смысл — одна реализация.
"""


def judge_eps() -> float:
    """Допуск СУДЬИ разбора: копейки округления бумаги, не процент (см. A выше)."""
    return 1.5


def pay_eps() -> int:
    """Гейт ДЕНЕГ ПРИЁМКИ: на сколько «оплачено по проводкам» имеет право разойтись
    с суммой прихода, прежде чем заказ считается недоплаченным или переплаченным.

    Целый сум и ни копейкой больше: копейки округления живут в ТЕКСТЕ подписи
    (`explain`), а сам гейт остаётся жёстким — иначе «почти оплачено» начинает
    двигать склад."""
    return 1


# ── D. АРИФМЕТИКА ОДНОЙ СТРОКИ ДОКУМЕНТА ───────────────────────────────────
# Допуск здесь ОТНОСИТЕЛЬНЫЙ, и это не противоречит пункту A: там процент судит
# ДОКУМЕНТ (и оправдывает потерю целой строки), здесь — произведение внутри ОДНОЙ
# строки, где цена напечатана округлённой и последние знаки законно не сходятся.
#
# Почему их ДВА, а не один. `pair_eps` ВЫБИРАЕТ: он ищет пару (цена, сумма) среди
# чисел строки, где рядом стоят «без НДС · сам НДС · с НДС», и широкий допуск
# выберет НЕ ТУ пару — отсюда 0,5 %. `row_eps` не выбирает ничего: он только
# ПОДПИСЫВАЕТ уже собранную строку полем `ok`, которое по построению слабое и
# судьёй качества не является (судья — `paper_invoice.line_read`), поэтому 1,5 %
# там безопасны. Свести их в одно число нельзя: узкий сломает подпись, широкий
# сломает выбор.
_ROW_REL = 0.015
_PAIR_REL = 0.005
_ROW_FLOOR = 2.0


def row_eps(summ) -> float:
    """Допуск САМОПРОВЕРКИ строки «кол-во × цена = сумма» (поле `ok`)."""
    return max(_ROW_FLOOR, abs(float(summ or 0)) * _ROW_REL)


def pair_eps(summ) -> float:
    """Допуск ПОИСКА пары (цена, сумма) внутри строки — узкий: он выбирает."""
    return max(_ROW_FLOOR, abs(float(summ or 0)) * _PAIR_REL)


def rounding_floor(n_lines: int = 0) -> float:
    """Пол допуска: 1 сум на строку документа (минимум 1) — тийины, которые бумага
    печатает, а приход считает в сумах."""
    return max(1.0, float(n_lines or 0))


def allowance(n_lines: int = 0, explained: float = 0.0) -> float:
    """Сколько денег расхождения ЗАКОННО объясняется округлением."""
    return max(rounding_floor(n_lines), abs(float(explained or 0)))


def covered(delta, n_lines: int = 0, explained: float = 0.0, hard: bool = False) -> bool:
    """Гасится ли расхождение `delta`. `hard=True` — повод из «НЕ гасит НИКОГДА»."""
    if hard:
        return False
    return abs(float(delta or 0)) <= allowance(n_lines, explained)


def explain(delta, n_lines: int = 0, explained: float = 0.0, hard: bool = False) -> str:
    """Подпись владельцу — ОДНА формулировка на всё приложение («подписывать,
    не схлопывать молча»)."""
    d = abs(float(delta or 0))
    if not d:
        return ""
    if covered(d, n_lines, explained, hard):
        return "разница %s сум = округление копеек накладной" % int(round(d))
    if hard:
        return "разница %s сум — НЕ округление: проверьте строку/цифры" % int(round(d))
    return "разница %s сум сверх допуска %s" % (int(round(d)),
                                                int(round(allowance(n_lines, explained))))
