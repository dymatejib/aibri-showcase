# ── склейка денег ──────────────────────────────────────────────────────────
def test_склейка_денег_только_целыми_ячейками():
    """Разряд тысяч, разорванный по соседним ячейкам, склеивается…"""
    assert pi.join_split_money("1 | Кофе | шт | 70 | 4 | 000,00 | 280 000,00") == \
        "1 | Кофе | шт | 70 |4000,00| 280 000,00"


def test_склейка_не_хватает_копеечный_хвост_соседнего_числа():
    """…но НЕ через границу копеек. Это корень целого класса ошибок: склейка
    «12 500.00» + «125 000» давала 12 500 001, парсер брал остаток суммой и
    вычислял цену делением — равенство становилось тождественным при 42 % потери
    денег."""
    raw = "2 | Чай | шт | 10 | 12 500.00 | 125 000 | 12% | 15 000.00 | 140 000.00"
    assert pi.join_split_money(raw) == raw


# ── чтение чисел ───────────────────────────────────────────────────────────
@pytest.mark.parametrize("cell,want", [
    ("10.000000", 10),          # количество, а не десять миллионов
    ("1 250 000.00", 1250000),  # ровно три цифры после разделителя = разряд тысяч
    ("240 000,00", 240000),
    ("1 320 000,70", 1320000.7),
    ("-42 500.00", -42500),     # знак скидки не теряется
    ("12%", 12),
    ("9167", 9167),
])
def test_число_ячейки(cell, want):
    assert pi.num_cell(cell) == want


@pytest.mark.parametrize("token,kind", [
    ("60", "qty"),                    # голое целое = количество
    ("17 500.00", "money"),           # разделитель разрядов = деньги
    ("1234567890128", "junk"),        # штрихкод деньгами быть не может
    ("12345678901234567890", "junk"),  # банковский счёт тоже
])
def test_вид_числа(token, kind):
    assert pi.classify_num(token)[0] == kind


# ── семейства бланков ──────────────────────────────────────────────────────
def test_блоки_разворачиваются_в_штуки(parsed):
    """Бумага печатает 10 блоков и цену за ШТУКУ. Наивный разбор кладёт на склад
    10 единиц вместо 120 и цену в двенадцать раз выше."""
    r = parsed["inv_01_header_pack"]
    line = r["lines"][0]
    assert (line["qty"], line["price"], line["sum"]) == (120, 2500, 300000)
    assert (line["pack_qty"], line["pack_size"]) == (10, 12)


def test_пустая_ячейка_не_сдвигает_колонки(parsed):
    """Пустая «Кол-во шт.» между «Кол-во бл.» и «Цена» не выпадает — иначе цена и
    сумма съезжают на колонку влево."""
    r = parsed["inv_01_header_pack"]
    assert [x["sum"] for x in r["lines"]] == [300000, 420000, 600000]


def test_строка_итога_не_становится_товаром(parsed):
    """«ВСЕГО | 120,00 кг | 156 | | | 1 320 000,00» — подытог, а не позиция с
    количеством 352 и ценой в 1,3 млн."""
    r = parsed["inv_01_header_pack"]
    assert len(r["lines"]) == 3
    assert all("ВСЕГО" not in x["name"] for x in r["lines"])


def test_вес_в_колонке_количества_не_товар():
    """Второй рубеж той же защиты — подытог без слова «всего»."""
    text = ("№ | Наименование | Кол-во бл. | Кол-во шт. | Цена | Сумма\n"
            "1 | Лимонад Дюшес | 2 | 24 | 5 000,00 | 120 000,00\n"
            "· | Сумма по весу | 120,00 кг |  |  | 120 000,00\n")
    lines = pi.parse_header_table(text)
    assert [x["name"] for x in lines] == ["Лимонад Дюшес"]


def test_ндс_плоскость_не_завышает_количество(parsed):
    """Цена без НДС, сумма с НДС: деление одного на другое даёт количество,
    завышенное ровно на ставку (20 → 22,4). Арифметика замыкается на прочитанном
    количестве, и только потом разбор поднимается в плоскость «с НДС»."""
    r = parsed["inv_02_unit_anchor_vat"]
    assert [x["qty"] for x in r["lines"]] == [20, 10]
    assert [x["sum"] for x in r["lines"]] == [280000, 280000]
    assert r["lines"][0]["price"] == 14000     # цена С НДС — закон приёмки


def test_роли_колонок_разводит_заголовок(parsed):
    """`кол-во × цена = сумма` симметрично: арифметика не отличает эти колонки.
    В документе порядок «Цена · Кол-во», и без заголовка разбор поменял бы их
    местами — 1 200 штук по 60 сум вместо 60 штук по 1 200."""
    r = parsed["inv_06_grid_roles"]
    assert r["family"] == "grid"
    assert [(x["qty"], x["price"]) for x in r["lines"]] == [(60, 1200), (40, 2500),
                                                            (80, 1500)]


def test_итог_прописью_включает_судью(texts, parsed):
    """У части бланков печатный итог только словами. Без него судья-арифметика
    выключается, и побеждает самый тавтологичный разбор."""
    assert pi.total_words(texts["inv_05_total_words"]) == 610000
    r = parsed["inv_05_total_words"]
    assert r["total_sum"] == 610000 and r["lines_sum"] == 610000


def test_процентный_судья_ломает_выбор_разбора(texts, monkeypatch):
    """ГЛАВНЫЙ ТЕЗИС ПРОЕКТА — ПРОВЕРЕННЫЙ, А НЕ ЗАЯВЛЕННЫЙ.

    Документ `inv_08_percent_judge` устроен так, как устроен живой: у последней
    строки (пакеты за 1 350 сум) в шапке пустая ячейка имени, поэтому разбор ПО
    ШАПКЕ её теряет, а разбор ПО ЯКОРЮ-ЕДИНИЦЕ находит имя строкой выше и читает
    все четыре. Итог документа — 1 396 350.

    Судья с копеечным допуском видит недостачу 1 350 сум и выбирает ПОЛНЫЙ разбор.
    Стоит сделать судью процентным (0,1 % = 1 396 сум — ровно то, что предлагалось
    как «инвариант»), и обрезанный разбор начинает «сходиться» с печатным итогом.
    Он стоит в очереди кандидатов первым — и побеждает. Строка на 1 350 сум исчезает
    с тем же зелёным видом, что и правильный разбор.

    Без этого теста закон L-04v2 держался на `assert judge_eps() == 1.5`, то есть
    на числе, а не на смысле."""
    text = texts["inv_08_percent_judge"]

    r = pi.parse_invoice(text)
    assert (r["family"], len(r["lines"])) == ("unit", 4)
    assert r["lines_sum"] == r["total_sum"] == 1_396_350
    assert r["hard_mismatch"] is False

    monkeypatch.setattr(tolerance, "judge_eps", lambda: 1_396_350 * 0.001)
    bad = pi.parse_invoice(text)
    assert (bad["family"], len(bad["lines"])) == ("hdr", 3)
    assert bad["lines_sum"] == 1_395_000          # строка на 1 350 сум просто исчезла
    assert 1_350 <= tolerance.judge_eps()         # процент её проглотил
    assert bad["hard_mismatch"] is True           # ловит уже только сверка с итогом


# ── что накладной НЕ является ──────────────────────────────────────────────
def test_прайс_лист_не_приходуется(texts, parsed):
    """Структурно это таблица товаров с количеством и суммой — и она бы
    оприходовалась. Не пускает маркер бланка, и он лежит в данных."""
    assert len(pi.parse_header_table(texts["inv_04_price_list"])) == 3
    assert "цена на полке" in pi.not_invoice_reason(texts["inv_04_price_list"])
    assert parsed["inv_04_price_list"] is None


def test_маркер_не_накладной_расширяется_данными(fresh_db):
    """Новый бланк-прайс = строка в таблицу, а не правка кода."""
    from aibri.recognition import corpus
    pi.patterns_reset()
    text = "СВОДКА ОСТАТКОВ\nПозиция | Кол-во | Цена | Сумма\nЛимонад | 2 | 100 | 200\n"
    assert pi.not_invoice_reason(text, [{"qty": 2}]) == ""
    corpus.learn_pattern("invoice", "not_invoice_marker", "marker:stock", "сводка остатков")
    pi.patterns_reset()
    try:
        assert "сводка остатков" in pi.not_invoice_reason(text, [{"qty": 2}])
    finally:
        pi.patterns_reset()


# ── честность ──────────────────────────────────────────────────────────────
def test_потерянная_строка_не_проглатывается_молча(parsed):
    """Распознавание потеряло разделитель ячеек, и строка не читается. Бот её не
    выдумывает — но и не молчит: печатный итог не сходится с суммой строк, это
    ЖЁСТКИЙ повод и вопрос владельцу."""
    r = parsed["inv_07_lost_line"]
    assert len(r["lines"]) == 2
    assert r["hard_mismatch"] is True and r["needs_owner"] is True
    assert r["total_diff"] == 60000
    assert "не хватает строки" in " ".join(r["warn"])


def test_честная_метрика_не_равна_тавтологии(parsed):
    """`ok` («кол-во × цена = сумма») выполняется по построению у всех разборов,
    которые хоть одно число вычисляют. `read` требует, чтобы количество и сумма
    были НАПЕЧАТАНЫ на одной строке документа."""
    for key in ("inv_01_header_pack", "inv_02_unit_anchor_vat", "inv_06_grid_roles"):
        r = parsed[key]
        assert all(x["read"] for x in r["lines"]), key
    fake = [{"qty": 3, "price": 100, "sum": 300}]
    assert pi.line_read(fake[0], [{7, 700}]) is False


def test_итог_не_может_быть_инн_или_счётом():
    """Позиционное правило: девятизначный ИНН из шапки проходит ограничение длины,
    но деньгами не является."""
    text = ("НАКЛАДНАЯ № 1234 от 01.01.2026\nИНН 111222333\n"
            "Позиция | Цена | Кол-во | Стоимость\n"
            "Лимонад Дюшес | 1 000 | 5 | 5 000\n"
            "ИТОГО |  |  | 5 000\n")
    assert 111222333 in pi.doc_nonmoney(text)
    assert pi.total_candidates(text) == [5000]


def test_рукописная_помета_только_после_цены():
    """«(не привезли)» после суммы — помета продавца. «(зелёный)» внутри имени —
    часть названия: иначе разные товары склеиваются в один."""
    assert pi.note_from("1 | Чай | шт | 10 | 8 000 (не привезли)") == "не привезли"
    assert pi.note_from("1 | Чай зелёный (крупный лист) | шт | 10 | 8 000") == ""


def test_лейбл_итога_расширяется_данными(fresh_db):
    from aibri.recognition import corpus
    pi.patterns_reset()
    text = ("Позиция | Цена | Кол-во | Сумма\n"
            "Лимонад Дюшес | 1 000 | 5 | 5 000\n"
            "Barchasi: 5 000\n")
    assert pi.total_candidates(text) == []
    corpus.learn_pattern("invoice", "total_label", "label:total", "barchasi")
    pi.patterns_reset()
    try:
        assert pi.total_candidates(text) == [5000]
    finally:
        pi.patterns_reset()
