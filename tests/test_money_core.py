"""Денежное ядро: единый формат и единый закон допуска."""
import pytest

from aibri.money import money as M
from aibri.money import tolerance as T


@pytest.mark.parametrize("value,want", [
    (1234567, "1 234 567"),
    (9165.33, "9 165,33"),      # тийины сохраняются и показываются запятой
    (9165.0, "9 165"),          # целое — без хвоста
    (-4500, "-4 500"),
    ("уточняется", "уточняется"),  # не число проходит насквозь
])
def test_формат_денег(value, want):
    assert M.money(value) == want


def test_разделитель_тысяч_обычный_пробел():
    """Ровно та ошибка, из-за которой формат и свели в один: один из вариантов
    разделял тысячи НЕРАЗРЫВНЫМ пробелом, и это было видно на экране."""
    assert " " not in M.money(1234567)


@pytest.mark.parametrize("raw,want", [
    ("12 500,50", 12500.5),     # владельцу не важно, точка или запятая
    ("12500.50", 12500.5),
    ("12 500", 12500.0),
    ("", 0.0),
    ("мусор", 0.0),
    ("-100", 0.0),              # отрицательных сумм ввода не бывает
])
def test_разбор_ввода_владельца(raw, want):
    assert M.parse_money(raw) == want


@pytest.mark.parametrize("value,want", [
    (128300, "128,3 к"),
    (3130000, "3,13 млн"),
    (12500000, "12,5 млн"),
    (-750, "-750"),
])
def test_витринный_формат(value, want):
    assert M.money_short(value) == want


# ── закон допуска ──────────────────────────────────────────────────────────
def test_судья_разбора_копеечный_а_не_процентный():
    """Процентный допуск оправдывает ПОТЕРЮ СТРОКИ: на документе с итогом
    1 400 000 сум 0,1 % = 1 400 сум, и обрезанный разбор без строки на 380 сум
    «сходился» с печатным итогом и побеждал полный."""
    assert T.judge_eps() == 1.5
    assert 1_400_000 * 0.001 > 380        # процентный допуск проглотил бы потерю
    assert T.judge_eps() < 380            # копеечный — нет


def test_вердикт_гасит_только_объяснённое_округление():
    # 12 строк документа, каждая округлена до сума → 12 сум объяснимы
    assert T.covered(12, n_lines=12) is True
    assert T.covered(13, n_lines=12) is False


def test_жёсткий_повод_не_гасится_никогда():
    """Печатный итог против суммы строк, недовоз и канальные расхождения — это
    либо потерянная строка, либо ошибка поставщика. Копейки их не объясняют."""
    assert T.covered(1, n_lines=100, hard=True) is False
    assert "НЕ округление" in T.explain(120000, n_lines=14, hard=True)


def test_формулировка_расхождения_одна_на_всё_приложение():
    assert T.explain(5, n_lines=12) == "разница 5 сум = округление копеек накладной"
    assert T.explain(0, n_lines=12) == ""
    assert "сверх допуска" in T.explain(500, n_lines=3)
