"""НАКЛОН КАДРА — чистая геометрия, и проверяется она на ВСЕХ ОС.

Почему отдельный файл. Подбор наклона — козырь фото-пути, но закрыт он был только
macOS-тестами: на Linux и Windows порча `frame_slope` не роняла вообще ничего.
При этом функция не знает ни про Vision, ни про macOS — на вход ей идут кортежи
`(текст, x, y, высота)`, и «снятую под углом» таблицу можно построить прямо здесь.

Класс ошибки, который тут воспроизведён: при наклоне ~8° по ширине таблицы правая
колонка уезжает вниз на несколько высот строки. Наивная группировка «по
горизонтали» сшивает в одну ленту количество ОДНОГО товара и сумму ДРУГОГО, и
никакой последующий разбор этого уже не исправит.
"""
import pytest

from aibri.recognition import ocr as O

ROWS, COLS = 6, 5
ROW_STEP = 0.045         # расстояние между строками документа, доли кадра
GLYPH_H = 0.012          # высота фрагмента: порог склейки строк берётся от неё
X0, X1 = 0.05, 0.95
XS = [X0 + (X1 - X0) * c / (COLS - 1) for c in range(COLS)]
TILT_8DEG = 0.14         # tg 8° ≈ 0,1405
STEP = 0.005             # шаг перебора углов в `frame_slope`


def page(slope):
    """Фрагменты страницы, «снятой» с заданным наклоном: `(текст, x, y, высота)`.
    Текст несёт номер своей настоящей строки — по нему и видно, перепутались ли они."""
    return [(f"r{r}c{c}", x, 1.0 - r * ROW_STEP + slope * x, GLYPH_H)
            for r in range(ROWS) for c, x in enumerate(XS)]


def rows_of(items, slope):
    """Группировка → списки текстов, как их склеил бы `ocr_image`."""
    return [[t for t, *_ in sorted(row, key=lambda f: f[1])]
            for row in O.rows_by_baseline(items, slope)]


@pytest.mark.parametrize("slope", [0.0, 0.05, TILT_8DEG, -TILT_8DEG, 0.2])
def test_наклон_подбирается_а_не_предполагается(slope):
    """Подобранный наклон совпадает с настоящим с точностью до шага перебора.

    Допуск в два шага — не запас «на всякий случай»: у идеально ровной сетки
    несколько соседних углов дают ОДИНАКОВО плотные строки, и ничья по правилу
    функции решается в пользу МЕНЬШЕГО угла. То есть ответ систематически лежит на
    ближней к нулю границе площадки, а не в её середине."""
    assert abs(O.frame_slope(page(slope)) - slope) <= 2 * STEP


def test_ровный_кадр_остаётся_ровным():
    """Ничья за меньшим углом: ровная бумага не должна «подкручиваться»."""
    assert O.frame_slope(page(0.0)) == 0.0


def test_при_верном_наклоне_строки_документа_целы():
    """Настоящий контракт слоя: не число, а ЦЕЛЫЕ строки документа на выходе."""
    items = page(TILT_8DEG)
    got = rows_of(items, O.frame_slope(items))
    assert len(got) == ROWS
    for row in got:
        r = row[0][1]                                  # «r3c0» → строка 3
        assert row == [f"r{r}c{c}" for c in range(COLS)]


def test_наивная_группировка_сшивает_разные_строки():
    """ДОКАЗАТЕЛЬСТВО, что подбор не украшение: с предположением «кадр ровный» тот
    же документ разваливается — в одной ленте оказываются фрагменты РАЗНЫХ строк."""
    got = rows_of(page(TILT_8DEG), 0.0)
    mixed = [row for row in got if len({t[1] for t in row}) > 1]
    assert mixed, "строки не перепутались — фикстура перестала воспроизводить класс ошибки"


def test_пустая_страница_не_роняет_подбор():
    """Vision вернул пусто (фото чёрное, бумага не попала в кадр) — наклон нулевой,
    а не исключение: наружу из этого слоя всегда уходит ответ."""
    assert O.frame_slope([]) == 0.0
    assert O.rows_by_baseline([], 0.0) == []
